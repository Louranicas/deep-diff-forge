#!/usr/bin/env python3
"""Render the README's terminal session (assets/terminal-session.svg) from real output.

Every line in the image is printed by the binary this script runs, against a fixed
input: the crate changes of PR #23 (`git diff 32fbb7d 2f03f40 -- crates`). Nothing is
typed by hand, so the picture cannot drift from the tool without a rerun showing it.

    cargo build -p deep-diff-forge-cli
    python3 scripts/docs/render_terminal_svg.py target/debug/deep-diff-forge
"""

import html
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RANGE = ("32fbb7d", "2f03f40")
RANK_LINES = 6

BG, BAR, FG, DIM, MUTED = "#13161a", "#1b2026", "#adbac7", "#6e7681", "#8b949e"
ACCENT, WARM, GREEN, RED, BLUE = "#d98a4f", "#e3a872", "#3fb950", "#f85149", "#79c0ff"
CHAR_W, LINE_H, PAD_X, TOP = 8.7, 21, 28, 64


def run(binary, args, stdin):
    done = subprocess.run([binary, *args], input=stdin, capture_output=True, check=False)
    return done.returncode, done.stdout.decode(), done.stderr.decode()


def session(binary):
    patch = subprocess.run(
        ["git", "diff", *RANGE, "--", "crates"], cwd=ROOT, capture_output=True, check=True
    ).stdout
    pipe = f"git diff {RANGE[0]} {RANGE[1]} -- crates | "
    blocks = []

    _, out, _ = run(binary, ["--stdin-patch", "--rank"], patch)
    lines = out.splitlines()
    blocks.append((pipe + "deep-diff-forge --stdin-patch --rank",
                   lines[:RANK_LINES] + ["   …"] + lines[-1:]))

    _, out, _ = run(binary, ["--stdin-patch", "--json", "--require-hunks"], patch)
    doc = json.loads(out)
    view = {key: doc[key] for key in ("schema", "input_sha256", "tool", "summary")}
    blocks.append((pipe + "deep-diff-forge --stdin-patch --json --require-hunks \\",
                   ["  | jq '{schema, input_sha256, tool, summary}'"]
                   + json.dumps(view, indent=2, ensure_ascii=False).splitlines()))

    code, _, err = run(binary, ["--stdin-patch", "--require-files"], b"")
    blocks.append(("deep-diff-forge --stdin-patch --require-files < /dev/null; echo \"exit $?\"",
                   err.splitlines() + [f"exit {code}"]))

    _, out, _ = run(binary, ["explain", str(code)], b"")
    blocks.append((f"deep-diff-forge explain {code}", out.splitlines()))
    return blocks


def span(text, fill):
    return f'<tspan fill="{fill}">{html.escape(text)}</tspan>'


def colour(line):
    """Colour one output line by what it is; the text itself is never changed."""
    rank = re.match(r"^(\s*\d+)(\s+)(\S+)(\s+)(\S+)(\s+)(\[.*\])$", line)
    if rank:
        score, s1, status, s2, path, s3, signals = rank.groups()
        return (span(score, WARM) + span(s1 + status + s2, DIM) + span(path, FG)
                + span(s3, FG) + span(signals, MUTED))
    key = re.match(r'^(\s*)("[^"]+")(: )(.*)$', line)
    if key:
        indent, name, sep, value = key.groups()
        fill = GREEN if value.startswith('"') else WARM
        return span(indent, FG) + span(name, BLUE) + span(sep, DIM) + span(value, fill)
    if line.startswith("  | jq "):
        return span(line, "#e6edf3")
    if line.startswith("refused:"):
        return span(line, RED)
    if line.startswith("exit "):
        return span("exit ", DIM) + span(line[5:], RED)
    if re.match(r"^engine \d+ ", line):
        head, _, rest = line.partition(": ")
        return span(head + ": ", WARM) + span(rest, FG)
    return span(line, MUTED if line.strip() in {"…", "{", "}"} else FG)


def render(blocks, version):
    rows = []
    for command, output in blocks:
        rows.append(span("$ ", ACCENT) + span(command, "#e6edf3"))
        rows.extend(colour(line) for line in output)
        rows.append("")
    rows.pop()
    width = int(PAD_X * 2 + CHAR_W * max(
        len(command) + 2 for command, _ in blocks))
    width = max(width, 1000)
    height = TOP + LINE_H * len(rows) + 24
    text = "\n".join(
        f'  <text x="{PAD_X}" y="{TOP + LINE_H * i}" xml:space="preserve">{row}</text>'
        for i, row in enumerate(rows) if row
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="t">
<title id="t">A terminal session: deep-diff-forge {version} ranks the files of a real change by review risk, prints its sealed JSON review, refuses empty input with exit 7, and explains exit code 7.</title>
<!-- Generated by scripts/docs/render_terminal_svg.py from the binary's real output. Do not edit by hand. -->
<rect width="{width}" height="{height}" rx="12" fill="{BG}"/>
<rect width="{width}" height="36" rx="12" fill="{BAR}"/>
<rect y="24" width="{width}" height="12" fill="{BAR}"/>
<circle cx="24" cy="18" r="6" fill="#f85149" fill-opacity="0.75"/>
<circle cx="44" cy="18" r="6" fill="#d29922" fill-opacity="0.75"/>
<circle cx="64" cy="18" r="6" fill="#3fb950" fill-opacity="0.75"/>
<text x="{width / 2}" y="23" text-anchor="middle" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="12.5" fill="{DIM}">deep-diff-forge {version} · real output, PR #23</text>
<g font-family="ui-monospace, SFMono-Regular, 'JetBrains Mono', Menlo, Consolas, monospace" font-size="14">
{text}
</g>
</svg>
"""


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: render_terminal_svg.py <deep-diff-forge binary>")
    binary = sys.argv[1]
    version = run(binary, ["--version"], b"")[1].split()[-1]
    out = ROOT / "assets" / "terminal-session.svg"
    out.write_text(render(session(binary), version), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
